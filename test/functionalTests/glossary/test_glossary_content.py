def get_cleaned_table_data(
    html_file_path, table_xpath, fix_format: bool = False, **kwargs
) -> dict:
    table_html = extract_table_by_xpath(html_file_path, table_xpath)
    table_data = html_table_as_dict(table_html, **kwargs)
    if fix_format:
        table_data = fix_former_glossary_formatting(table_data)
    data = normalize_text(
        table_data,
        keys=["Definition", "Data type / cardinality", "Domain, Range and Cardinality"],
    )
    if SAVE_JSON_DATA_FOR_DEBUG:
        debug_file_path = TEST_OUTPUT_DATA_PATH / str(
            html_file_path.name + table_xpath.replace("/", "_") + ".json"
        )
        with open(debug_file_path, "w") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
    return data


