@pytest.mark.parametrize(
    "former_glossary_table_data,asciidoc_glossary_table_data",
    [
        (
            "former_gloss_classes_data_wo_reused_concepts",
            "asciidoc_gloss_classes_data_wo_reused_concepts",
        ),
        (
            "former_gloss_classes_data_with_reused_concepts",
            "asciidoc_gloss_classes_data_with_reused_concepts",
        ),
    ],
    indirect=True,
)
def test_compare_classes_for_two_glossary_versions(
    former_glossary_table_data: dict,
    asciidoc_glossary_table_data: dict,
):
    """
    Compares glossary table entries for classes.

    This test checks the AsciiDoc glossary content against the former HTML
    glossary by extracting and normalizing relevant table data from both
    sources. The test checks if values of the table cells for the same
    properties match.
    """
    diff = DeepDiff(
        former_glossary_table_data,
        asciidoc_glossary_table_data,
        ignore_order=True,
        report_repetition=True,
        verbose_level=2,
    ).pretty()
    print(diff)
    assert (
        not diff
    ), f"The AsciiDoc glossary does not match the former HTML version: {diff}"


@pytest.mark.parametrize(
    "former_glossary_table_data,asciidoc_glossary_table_data,filter_func",
    [
        (
            "former_gloss_attrs_data_with_reused_concepts",
            "asciidoc_gloss_attrs_data_with_reused_concepts",
            lambda a: not is_attribute_name_shared(a),
        ),
        (
            "former_gloss_attrs_data_wo_reused_concepts",
            "asciidoc_gloss_attrs_data_wo_reused_concepts",
            lambda a: not is_attribute_name_shared(a),
        ),
        (
            "former_gloss_rels_data_with_reused_concepts",
            "asciidoc_gloss_rels_data_with_reused_concepts",
            lambda r: not is_relationship_name_shared(r),
        ),
        (
            "former_gloss_rels_data_wo_reused_concepts",
            "asciidoc_gloss_rels_data_wo_reused_concepts",
            lambda r: not is_relationship_name_shared(r),
        ),
    ],
    indirect=["former_glossary_table_data", "asciidoc_glossary_table_data"],
)
def test_compare_unique_properties_for_two_glossary_versions(
    former_glossary_table_data: dict,
    asciidoc_glossary_table_data: dict,
    filter_func: Callable,
):
    """
    Compares glossary table entries for attributes and relationships
    (predicates) whose names are not reused across multiple classes or
    relations.

    This test checks the AsciiDoc glossary content against the former HTML
    glossary by extracting and normalizing relevant table data from both
    sources.
    The test checks if values of the table cells for the same properties match.
    """
    try:
        diff = DeepDiff(
            [r for r in former_glossary_table_data if filter_func(r)],
            [r for r in asciidoc_glossary_table_data if filter_func(r)],
            ignore_order=True,
            report_repetition=True,
            verbose_level=2,
        )
        diff_str = diff.pretty()
        print()
        assert (
            not diff_str
        ), f"The AsciiDoc glossary does not match the former HTML version: {diff_str}"
    except AssertionError:
        # ignore any differences caused due to different spacing
        matching = []
        for k, v in diff["values_changed"].items():
            if v["new_value"].replace(" ", "") == v["old_value"].replace(" ", ""):
                matching.append(k)
        for k in matching:
            diff["values_changed"].pop(k, None)
        if diff["values_changed"]:
            raise  # raises the original error if at least one difference remains


@pytest.mark.parametrize(
    "former_glossary_table_data,asciidoc_glossary_table_data,filter_func,preprocess_func",
    [
        (
            "former_gloss_attrs_data_with_reused_concepts",
            "asciidoc_gloss_attrs_data_with_reused_concepts",
            is_attribute_name_shared,
            preprocess_shared_attribute_data,
        ),
        (
            "former_gloss_attrs_data_wo_reused_concepts",
            "asciidoc_gloss_attrs_data_wo_reused_concepts",
            is_attribute_name_shared,
            preprocess_shared_attribute_data,
        ),
        (
            "former_gloss_rels_data_with_reused_concepts",
            "asciidoc_gloss_rels_data_with_reused_concepts",
            is_relationship_name_shared,
            preprocess_shared_relationship_data,
        ),
        (
            "former_gloss_rels_data_wo_reused_concepts",
            "asciidoc_gloss_rels_data_wo_reused_concepts",
            is_relationship_name_shared,
            preprocess_shared_relationship_data,
        ),
    ],
    indirect=["former_glossary_table_data", "asciidoc_glossary_table_data"],
)
def test_compare_shared_properties_for_two_glossary_versions(
    former_glossary_table_data: dict,
    asciidoc_glossary_table_data: dict,
    filter_func: Callable,
    preprocess_func: Callable,
    request,
):
    """
    Compares glossary table entries for attributes and relationships
    (predicates) whose names are reused across multiple classes or relations.

    This test checks the AsciiDoc glossary content against the former HTML
    glossary by extracting and normalizing relevant table data from both
    sources.
    The test checks if values of the table cells for the same properties match.
    Testing of definitions is handled differently due to repetitions in the
    former glossary.
    """
    expected = [
        preprocess_func(r) for r in former_glossary_table_data if filter_func(r)
    ]
    actual = [
        preprocess_func(r) for r in asciidoc_glossary_table_data if filter_func(r)
    ]
    diff = DeepDiff(
        expected, actual, ignore_order=True, report_repetition=True, verbose_level=2
    ).pretty()
    print(diff)
    with save_on_assert_failure(
        SAVE_JSON_DATA_FOR_DEBUG,
        build_debug_file_path(request, "former"),
        expected,
        build_debug_file_path(request, "asciidoc"),
        actual,
    ):
        assert (
            not diff
        ), f"The AsciiDoc glossary does not match the former HTML version: {diff}"

    # Handle definitions separately

    # key used to identify and index entries
    key = (
        "Attribute name"
        if "Attribute name" in former_glossary_table_data[0]
        else "Predicate name"
    )
    asciidoc_glossary_table_data_idx = build_index(asciidoc_glossary_table_data, key)

    for r in former_glossary_table_data:
        asciidoc_gloss_def = asciidoc_glossary_table_data_idx[r[key]]["Definition"]
        expected_def = r["Definition"]
        # need to remove spaces for comparision due to formatting differences
        # caused by invalid concatenation in the former glossary
        assert asciidoc_gloss_def.replace(" ", "") in expected_def.replace(" ", ""), (
            f"The definition for '{r[key]}' does not match: "
            f"expected '{expected_def}', got '{asciidoc_gloss_def}'"
        )
